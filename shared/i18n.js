  function currentLang() {
    const lang = String(document.documentElement.lang || 'it').toLowerCase();
    return lang.indexOf('en') === 0 ? 'en' : 'it';
  }

  function lookup(key) {
    const pack = messages[currentLang()] || messages.it || {};
    const fallback = messages.it || {};
    if (Object.prototype.hasOwnProperty.call(pack, key)) return pack[key];
    if (Object.prototype.hasOwnProperty.call(fallback, key)) return fallback[key];
    return key;
  }

  function t(key, vars) {
    let value = lookup(key);
    if (vars) {
      Object.keys(vars).forEach(name => {
        value = String(value).split('{' + name + '}').join(vars[name] == null ? '' : String(vars[name]));
      });
    }
    return value;
  }

  function asset(path) {
    if (path == null || path === '') return path;
    const value = String(path);
    if (/^(?:[a-z][a-z0-9+.-]*:|\/\/|#|\/|\.\.)/i.test(value)) return value;
    const base = document.documentElement.getAttribute('data-asset-base') || '';
    return base + value.replace(/^\.\//, '');
  }

